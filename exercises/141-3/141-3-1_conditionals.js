// [미션 1] 성적 등급 매기기
const studentScore = 88;
let grade = "";

// TODO: score가 90 이상이면 "A", 80 이상 90 미만이면 "B", 그 미만이면 "C"를 grade에 담으세요.
if (studentScore >= 90) {
    grade = "A";
} else if (studentScore >= 80) {
    grade = "B";
} else {
    grade = "C";
}

console.log(` 1-1. 학생의 최종 학점 판정: ${grade} 등급`);
console.log("--------------------------------------------------");

// [미션 2] Truthy / Falsy 판정 및 암묵적 형 변환 관찰
// 자바스크립트는 조건식 안에서 0, 빈 문자열(""), null, undefined 등을 Falsy(거짓 같은 값)로 판정합니다.

const userNickname = ""; // 빈 문자열 (Falsy 데이터)
const activeUsers = 0;   // 숫자 0 (Falsy 데이터)

// TODO: 아래 조건식의 빈 자리를 채우거나 해석해 보세요.
if (userNickname) {
    console.log(" 1-2. 닉네임이 존재합니다.");
} else {
    console.log(" 1-2. 닉네임이 비어 있어 Falsy로 판정되었습니다.");
}

if (!activeUsers) {
    console.log(" 1-3. 활성 사용자가 0명이므로 참(!0 => true)으로 판정되었습니다.");
}
console.log("==================================================");
