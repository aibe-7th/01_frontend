console.log("==================================================");

// [미션 1] 배열의 기본적인 CRUD 및 splice 제어
const fruits = ["사과", "바나나"];

// TODO 1-1: push를 이용하여 뒤쪽에 "체리"를 추가하세요. (Create)
fruits.push("체리");

// TODO 1-2: 인덱스를 사용해 1번 자리("바나나")를 "메론"으로 수정하세요. (Update)
fruits[1] = "메론";

// TODO 1-3: splice를 사용하여 1번 자리("메론")를 완전히 들어내고 대신 "포도"를 그 자리에 삽입하세요.
fruits.splice(1, 1, "포도");

console.log(" 2-1. fruits 최종 배열 상태:", fruits); // ["사과", "포도", "체리"]

// [추가 연습 2-1] 장바구니 배열 cart를 활용해 아래 미션을 수행하세요.
// 1. ["우유", "빵"] 배열 생성
// 2. 뒤쪽에 "계란" 추가
// 3. 앞쪽에 "두부" 추가 (힌트: unshift 사용)
// 4. splice를 이용해 2번 인덱스의 물건을 제거하고 대신 "치즈" 삽입
const cart = ["우유", "빵"];
cart.push("계란");
cart.unshift("두부");
cart.splice(2, 1, "치즈");
console.log(" 2-2. cart 추가 연습 결과:", cart); // ["두부", "우유", "치즈", "계란"]

console.log("--------------------------------------------------");

// [미션 2] 배열 정렬 (Sort)
const numbers = [4, 2, 10, 25];

// TODO 2-1: a, b 두 값을 정렬 비교 함수로 빼서 오름차순(Ascending) 정렬되도록 식을 완성하세요.
numbers.sort((a, b) => a - b);
console.log(" 2-3. 올바른 오름차순 정렬:", numbers); // [2, 4, 10, 25]

// TODO 2-2: 내림차순(Descending)으로 정렬되도록 비교 정렬 함수를 완성하세요.
numbers.sort((a, b) => b - a);
console.log(" 2-4. 올바른 내림차순 정렬:", numbers); // [25, 10, 4, 2]

// [추가 연습 2-2] 학생 성적 배열 scores가 주어졌을 때 점수가 높은 순(내림차순)으로 바르게 정렬해 출력해 보세요.
const scores = [88, 92, 76, 95, 100];
scores.sort((a, b) => b - a);
console.log(" 2-5. 성적 고득점순 정렬 결과:", scores); // [100, 95, 92, 88, 76]
